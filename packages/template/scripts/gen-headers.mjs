












































import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DENIED_FEATURES, buildPolicy, measureClient, walkHtml } from './lib/csp.mjs';

const distRoot = join(fileURLToPath(new URL('.', import.meta.url)), '..', 'dist');

function generate(slug) {
  const distDir = join(distRoot, slug);
  if (!existsSync(distDir)) {
    console.error(`✗ ${slug}: no dist/${slug}. Run a build first.`);
    return false;
  }
  if (walkHtml(distDir).length === 0) {
    console.error(`✗ ${slug}: no HTML in dist/${slug}.`);
    return false;
  }

  const { merged } = measureClient(distDir);

  // A page with an executable inline script that produced no hash would mean
  // the policy is about to break that page. Fail rather than ship it.
  if (merged.unhashable.length > 0) {
    console.error(`\n✗ ${slug}: inline script(s) could not be hashed:\n`);
    for (const u of merged.unhashable) console.error(`    ${u}`);
    return false;
  }

  const policy = buildPolicy(merged);
  const body = [
    '# Generated by scripts/gen-headers.mjs — do not edit by hand.',
    '#',
    '# The CSP is measured from this build\'s own HTML: one hash per inline',
    '# script, and only the origins the pages actually reference. Rebuilding',
    '# regenerates it; scripts/check-headers.mjs fails the build if this file',
    '# and the HTML ever disagree.',
    '',
    '/*',
    `  Content-Security-Policy: ${policy}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    // Redundant against frame-ancestors for any current browser, and one line
    // for the ones that predate it.
    '  X-Frame-Options: DENY',
    `  Permissions-Policy: ${DENIED_FEATURES.map((f) => `${f}=()`).join(', ')}`,
    '',
  ].join('\n');

  writeFileSync(join(distDir, '_headers'), body, 'utf8');

  // Reported off the policy that was actually written, not off the inputs, so
  // the line cannot describe a policy different from the one on disk.
  const frameSrc = /frame-src ([^;]+)/.exec(policy)?.[1] ?? '?';
  console.log(
    `✓ ${slug}: _headers written — ${merged.hashes.size} script hash(es), ` +
      `${merged.scriptHosts.size} external script host(s), ` +
      `${merged.connectHosts.size} connect host(s), frame-src ${frameSrc}.`,
  );
  return true;
}

const requested = process.argv[2];
let slugs;
try {
  if (requested === '--all') {
    slugs = readdirSync(distRoot).filter((d) => statSync(join(distRoot, d)).isDirectory());
  } else {
    slugs = [requested || process.env.SITE_CLIENT || 'portfolio-ironvale-fabrication'];
  }
} catch {
  console.error('No dist/ directory. Run a build first.');
  process.exit(1);
}

const results = slugs.map(generate);
process.exit(results.every(Boolean) ? 0 : 1);
